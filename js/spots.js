const MONTHS = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December"
];

// Builds a 12-month direction array. Months not listed in `b` get direction `a`.
function seasonal(a, b, bMonths) {
  return MONTHS.map((_, i) => (bMonths.includes(i + 1) ? b : a));
}

